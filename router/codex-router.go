package router

import (
	"github.com/QuantumNous/new-api/controller"
	"github.com/QuantumNous/new-api/middleware"
	"github.com/gin-gonic/gin"
)

func setCodexWorkbenchRouter(api *gin.RouterGroup) {
	tools := api.Group("/codex/tools", middleware.CodexToolsAuth(), middleware.DisableCache())
	tools.GET("/catalog", controller.CodexToolsCatalog)
	tools.POST("/call", controller.CodexToolsCall)
	admin := api.Group("/codex-admin", middleware.AdminAuth(), middleware.DisableCache())
	admin.GET("/users", controller.ListCodexAdminUsers)
	admin.GET("/users/:id", controller.GetUserCodexConfig)
	admin.PUT("/users/:id", controller.UpdateUserCodexConfig)

	group := api.Group("/codex", middleware.CodexWorkbenchAuth(), middleware.DisableCache())
	group.GET("/catalog", controller.CodexCatalog)
	group.GET("/search", controller.CodexWorkbenchProxy)
	group.GET("/tasks", controller.CodexWorkbenchProxy)
	group.GET("/github", controller.CodexGitHubStatus)
	group.POST("/github/authorize", controller.CodexGitHubAuthorize)
	group.POST("/github/callback", controller.CodexGitHubCallback)
	group.DELETE("/github", controller.CodexGitHubDisconnect)
	group.GET("/github/repositories", controller.CodexGitHubRepositories)
	group.GET("/github/pulls", controller.CodexWorkbenchProxy)
	group.GET("/github/pulls/:owner/:repo/:number", controller.CodexWorkbenchProxy)
	group.GET("/github/pulls/:owner/:repo/:number/context", controller.CodexWorkbenchProxy)
	group.POST("/github/pulls/:owner/:repo/:number/comments", controller.CodexWorkbenchProxy)
	group.POST("/github/pulls/:owner/:repo/:number/reviews", controller.CodexWorkbenchProxy)
	group.POST("/github/pulls/:owner/:repo/:number/task", controller.CodexWorkbenchProxy)
	group.POST("/ssh/probe", controller.CodexWorkbenchProxy)
	group.GET("/ssh/connections", controller.CodexWorkbenchProxy)
	group.POST("/ssh/connections", controller.CodexWorkbenchProxy)
	group.DELETE("/ssh/connections/:id", controller.CodexWorkbenchProxy)
	group.POST("/ssh/connections/:id/test", controller.CodexWorkbenchProxy)
	group.GET("/status", controller.CodexWorkbenchProxy)
	group.GET("/environment", controller.CodexWorkbenchProxy)
	group.POST("/environment/start", controller.CodexWorkbenchProxy)
	group.POST("/environment/stop", controller.CodexWorkbenchProxy)
	group.GET("/environment/ports", controller.CodexWorkbenchProxy)
	group.POST("/environment/ports", controller.CodexWorkbenchProxy)
	group.DELETE("/environment/ports/:id", controller.CodexWorkbenchProxy)
	group.GET("/environments", controller.CodexWorkbenchProxy)
	group.POST("/environments", controller.CodexWorkbenchProxy)
	group.GET("/environments/:id", controller.CodexWorkbenchProxy)
	group.PATCH("/environments/:id", controller.CodexWorkbenchProxy)
	group.DELETE("/environments/:id", controller.CodexWorkbenchProxy)
	group.POST("/environments/:id/setup", controller.CodexWorkbenchProxy)
	group.POST("/environments/:id/publish", controller.CodexWorkbenchProxy)
	group.POST("/environments/:id/tasks", controller.CodexWorkbenchProxy)
	group.GET("/workspaces", controller.CodexWorkbenchProxy)
	group.POST("/workspaces", controller.CodexWorkbenchProxy)
	group.GET("/workspaces/:id", controller.CodexWorkbenchProxy)
	group.PATCH("/workspaces/:id", controller.CodexWorkbenchProxy)
	group.DELETE("/workspaces/:id", controller.CodexWorkbenchProxy)
	group.GET("/workspaces/:id/conversations", controller.CodexWorkbenchProxy)
	group.POST("/workspaces/:id/conversations", controller.CodexWorkbenchProxy)
	group.PATCH("/workspaces/:id/conversations/:conversationId", controller.CodexWorkbenchProxy)
	group.DELETE("/workspaces/:id/conversations/:conversationId", controller.CodexWorkbenchProxy)
	group.DELETE("/workspaces/:id/queue/:requestId", controller.CodexWorkbenchProxy)
	group.POST("/workspaces/:id/turns", controller.CodexWorkbenchProxy)
	group.DELETE("/workspaces/:id/turns/:turnId/messages/:role", controller.CodexWorkbenchProxy)
	group.POST("/workspaces/:id/interrupt", controller.CodexWorkbenchProxy)
	group.POST("/workspaces/:id/approvals/:requestId", controller.CodexWorkbenchProxy)
	group.GET("/workspaces/:id/events", controller.CodexWorkbenchProxy)
	group.GET("/workspaces/:id/files", controller.CodexWorkbenchProxy)
	group.GET("/workspaces/:id/file", controller.CodexWorkbenchProxy)
	group.GET("/workspaces/:id/download", controller.CodexWorkbenchProxy)
	group.PUT("/workspaces/:id/file", controller.CodexWorkbenchProxy)
	group.GET("/workspaces/:id/diff", controller.CodexWorkbenchProxy)
	group.GET("/workspaces/:id/repository", controller.CodexWorkbenchProxy)
	group.POST("/workspaces/:id/repository/checkout", controller.CodexWorkbenchProxy)
	group.GET("/workspaces/:id/git/status", controller.CodexWorkbenchProxy)
	group.POST("/workspaces/:id/git/commit", controller.CodexWorkbenchProxy)
	group.POST("/workspaces/:id/git/push", controller.CodexWorkbenchProxy)
	group.POST("/workspaces/:id/git/pull-request", controller.CodexWorkbenchProxy)
	group.POST("/workspaces/:id/import", controller.CodexWorkbenchProxy)
	group.POST("/workspaces/:id/upload", controller.CodexWorkbenchProxy)
	group.GET("/workspaces/:id/export", controller.CodexWorkbenchProxy)
}
