package model

import (
	"errors"
	"strings"
	"time"

	"github.com/QuantumNous/new-api/common"
	sqliteDriver "github.com/glebarez/go-sqlite"
	"gorm.io/gorm"
)

var (
	ErrOAuthGrantInvalid   = errors.New("oauth grant or token is invalid")
	ErrOAuthRefreshReplay  = errors.New("oauth refresh token was already used")
	ErrOAuthScopeExpansion = errors.New("oauth grant cannot be expanded")
)

// OAuthGrant is a snapshot of one explicit authorization. Tokens refer to its
// version, so revocation and narrowing invalidate every associated credential.
type OAuthGrant struct {
	ID                  int    `json:"id" gorm:"primaryKey"`
	UserID              int    `json:"user_id" gorm:"not null;index:idx_oauth_grants_user_created,priority:1"`
	OAuthClientID       int    `json:"oauth_client_id" gorm:"column:oauth_client_id;not null;index"`
	Scopes              string `json:"scopes" gorm:"type:text;not null"`
	Resources           string `json:"resources" gorm:"type:text;not null"`
	UserAuthVersion     int64  `json:"-" gorm:"not null"`
	UserAuthFingerprint string `json:"-" gorm:"type:varchar(64);not null"`
	ClientAuthVersion   string `json:"-" gorm:"type:varchar(64);not null"`
	Version             int64  `json:"version" gorm:"not null"`
	CreatedAt           int64  `json:"created_at" gorm:"not null;index:idx_oauth_grants_user_created,priority:2"`
	ExpiresAt           int64  `json:"expires_at" gorm:"not null;index"`
	RevokedAt           int64  `json:"revoked_at" gorm:"not null;default:0"`
}

// OAuthAccessToken stores only a SHA-256 verifier. Raw bearer credentials are
// generated by the service and never enter a database model.
type OAuthAccessToken struct {
	ID           int    `json:"-" gorm:"primaryKey"`
	GrantID      int    `json:"-" gorm:"not null;index"`
	GrantVersion int64  `json:"-" gorm:"not null"`
	TokenHash    string `json:"-" gorm:"type:varchar(64);not null;unique"`
	CreatedAt    int64  `json:"-" gorm:"not null"`
	ExpiresAt    int64  `json:"-" gorm:"not null;index"`
}

// OAuthRefreshToken rows are retained after rotation to detect reuse of any
// ancestor in the family, rather than only the immediately preceding token.
type OAuthRefreshToken struct {
	ID           int    `json:"-" gorm:"primaryKey"`
	GrantID      int    `json:"-" gorm:"not null;index"`
	GrantVersion int64  `json:"-" gorm:"not null"`
	TokenHash    string `json:"-" gorm:"type:varchar(64);not null;unique"`
	CreatedAt    int64  `json:"-" gorm:"not null"`
	ExpiresAt    int64  `json:"-" gorm:"not null;index"`
	ConsumedAt   int64  `json:"-" gorm:"not null;default:0"`
}

func (OAuthGrant) TableName() string        { return "oauth_grants" }
func (OAuthAccessToken) TableName() string  { return "oauth_access_tokens" }
func (OAuthRefreshToken) TableName() string { return "oauth_refresh_tokens" }

func validOAuthTokenHash(hash string) bool {
	if len(hash) != 64 {
		return false
	}
	for _, char := range hash {
		if (char < '0' || char > '9') && (char < 'a' || char > 'f') {
			return false
		}
	}
	return true
}

func retryableOAuthSQLiteConflict(err error, attempt int) bool {
	var sqliteError *sqliteDriver.Error
	return common.UsingMainDatabase(common.DatabaseTypeSQLite) && attempt < 4 &&
		errors.As(err, &sqliteError) && (sqliteError.Code()&0xff == 5 || sqliteError.Code()&0xff == 6)
}

// ConsumeOAuthAuthorizationFlow preserves single-use authorization codes on
// SQLite when competing transactions initially read the same unused snapshot.
// The action must keep all writes inside tx and recreate any attempt-local
// model values because a rolled-back transaction can still populate their IDs.
func ConsumeOAuthAuthorizationFlow(code string, action func(*gorm.DB, *AuthFlow) error) (*AuthFlow, error) {
	for attempt := 0; ; attempt++ {
		flow, err := ConsumeAuthFlowWithAction(code, AuthFlowMatch{Purpose: "oidc_code"}, action)
		if err == nil || !retryableOAuthSQLiteConflict(err, attempt) {
			return flow, err
		}
		time.Sleep(time.Duration(5<<attempt) * time.Millisecond)
	}
}

// GetConsumedOAuthAuthorizationFlow is used only after replay detection. Its
// payload binds the consumed code to the original grant, client and verifier;
// callers must validate those bindings before revoking that grant.
func GetConsumedOAuthAuthorizationFlow(code string) (*AuthFlow, error) {
	if code == "" {
		return nil, ErrAuthFlowInvalid
	}
	var flow AuthFlow
	err := DB.Where("token_hash = ? AND purpose = ? AND consumed_at IS NOT NULL", authFlowTokenHash(code), "oidc_code").First(&flow).Error
	if errors.Is(err, gorm.ErrRecordNotFound) {
		return nil, ErrAuthFlowInvalid
	}
	if err != nil {
		return nil, err
	}
	return &flow, nil
}

func CreateOAuthGrant(grant *OAuthGrant) error {
	return CreateOAuthGrantWithTx(DB, grant)
}

// CreateOAuthGrantWithTx lets authorization-code consumption and grant
// creation share one transaction, so a failed issuance cannot burn the code.
func CreateOAuthGrantWithTx(tx *gorm.DB, grant *OAuthGrant) error {
	if tx == nil {
		return ErrOAuthGrantInvalid
	}
	now := time.Now().Unix()
	if grant == nil || grant.ID != 0 || grant.UserID <= 0 || grant.OAuthClientID <= 0 ||
		grant.ExpiresAt <= now || grant.UserAuthVersion <= 0 ||
		strings.TrimSpace(grant.UserAuthFingerprint) == "" || strings.TrimSpace(grant.ClientAuthVersion) == "" {
		return ErrOAuthGrantInvalid
	}
	grant.Scopes = strings.Join(normalizeOauthScopes(strings.Fields(grant.Scopes)), " ")
	var resources []string
	if grant.Scopes == "" || common.UnmarshalJsonStr(grant.Resources, &resources) != nil || len(resources) == 0 {
		return ErrOAuthGrantInvalid
	}
	for _, resource := range resources {
		if strings.TrimSpace(resource) == "" {
			return ErrOAuthGrantInvalid
		}
	}
	grant.Version = 1
	grant.CreatedAt = now
	grant.RevokedAt = 0
	return tx.Create(grant).Error
}

// GetOAuthGrantByID intentionally reads the current database state. Callers
// must compare their token's version and validate the current user and client.
func GetOAuthGrantByID(id int) (*OAuthGrant, error) {
	if id <= 0 {
		return nil, ErrOAuthGrantInvalid
	}
	var grant OAuthGrant
	if err := DB.Where("id = ? AND revoked_at = 0 AND expires_at > ?", id, time.Now().Unix()).First(&grant).Error; err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			return nil, ErrOAuthGrantInvalid
		}
		return nil, err
	}
	return &grant, nil
}

func insertOAuthTokenPair(tx *gorm.DB, grant *OAuthGrant, accessHash, refreshHash string, accessExpiresAt, refreshExpiresAt, now int64) error {
	if !validOAuthTokenHash(accessHash) || accessExpiresAt <= now ||
		(refreshHash != "" && (!validOAuthTokenHash(refreshHash) || refreshHash == accessHash || refreshExpiresAt <= now)) {
		return ErrOAuthGrantInvalid
	}
	if accessExpiresAt > grant.ExpiresAt {
		accessExpiresAt = grant.ExpiresAt
	}
	if refreshExpiresAt > grant.ExpiresAt {
		refreshExpiresAt = grant.ExpiresAt
	}
	access := OAuthAccessToken{GrantID: grant.ID, GrantVersion: grant.Version, TokenHash: accessHash, CreatedAt: now, ExpiresAt: accessExpiresAt}
	if err := tx.Create(&access).Error; err != nil {
		return err
	}
	if refreshHash == "" {
		return nil
	}
	refresh := OAuthRefreshToken{GrantID: grant.ID, GrantVersion: grant.Version, TokenHash: refreshHash, CreatedAt: now, ExpiresAt: refreshExpiresAt}
	return tx.Create(&refresh).Error
}

// IssueOAuthTokenPair issues the first pair only. Subsequent pairs must go
// through rotation, which keeps the family single-branched and replay-aware.
func IssueOAuthTokenPair(grantID int, accessHash, refreshHash string, accessExpiresAt, refreshExpiresAt int64) error {
	return DB.Transaction(func(tx *gorm.DB) error {
		return IssueOAuthTokenPairWithTx(tx, grantID, accessHash, refreshHash, accessExpiresAt, refreshExpiresAt)
	})
}

// IssueOAuthTokenPairWithTx requires a caller-owned transaction and never
// commits independently from the authorization code that created the grant.
func IssueOAuthTokenPairWithTx(tx *gorm.DB, grantID int, accessHash, refreshHash string, accessExpiresAt, refreshExpiresAt int64) error {
	if tx == nil {
		return ErrOAuthGrantInvalid
	}
	now := time.Now().Unix()
	var grant OAuthGrant
	if err := lockForUpdate(tx).Where("id = ? AND revoked_at = 0 AND expires_at > ?", grantID, now).First(&grant).Error; err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			return ErrOAuthGrantInvalid
		}
		return err
	}
	var count int64
	if err := tx.Model(&OAuthAccessToken{}).Where("grant_id = ?", grant.ID).Count(&count).Error; err != nil {
		return err
	}
	if count != 0 {
		return ErrOAuthGrantInvalid
	}
	return insertOAuthTokenPair(tx, &grant, accessHash, refreshHash, accessExpiresAt, refreshExpiresAt, now)
}

func GetOAuthAccessGrant(hash string) (*OAuthGrant, error) {
	if !validOAuthTokenHash(hash) {
		return nil, ErrOAuthGrantInvalid
	}
	var token OAuthAccessToken
	if err := DB.Where("token_hash = ? AND expires_at > ?", hash, time.Now().Unix()).First(&token).Error; err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			return nil, ErrOAuthGrantInvalid
		}
		return nil, err
	}
	grant, err := GetOAuthGrantByID(token.GrantID)
	if err != nil {
		return nil, err
	}
	if token.GrantVersion != grant.Version {
		return nil, ErrOAuthGrantInvalid
	}
	return grant, nil
}

// GetOAuthRefreshGrant is a state-prevalidation lookup. It deliberately also
// returns the grant for consumed tokens so RotateOAuthRefreshToken can commit
// family revocation when one of those tokens is presented again.
func GetOAuthRefreshGrant(hash string, clientID int) (*OAuthGrant, error) {
	if !validOAuthTokenHash(hash) || clientID <= 0 {
		return nil, ErrOAuthGrantInvalid
	}
	var token OAuthRefreshToken
	if err := DB.Where("token_hash = ?", hash).First(&token).Error; err != nil {
		if errors.Is(err, gorm.ErrRecordNotFound) {
			return nil, ErrOAuthGrantInvalid
		}
		return nil, err
	}
	grant, err := GetOAuthGrantByID(token.GrantID)
	if err != nil {
		return nil, err
	}
	if grant.OAuthClientID != clientID || token.GrantVersion != grant.Version {
		return nil, ErrOAuthGrantInvalid
	}
	if token.ConsumedAt == 0 && token.ExpiresAt <= time.Now().Unix() {
		return nil, ErrOAuthGrantInvalid
	}
	return grant, nil
}

// RotateOAuthRefreshToken consumes the old verifier and inserts the next pair
// atomically. Replay is reported only after its revocation transaction commits.
func RotateOAuthRefreshToken(hash string, clientID int, nextAccessHash, nextRefreshHash string, accessExpiresAt, refreshExpiresAt int64) (*OAuthGrant, error) {
	if !validOAuthTokenHash(hash) || clientID <= 0 || !validOAuthTokenHash(nextAccessHash) ||
		!validOAuthTokenHash(nextRefreshHash) || hash == nextRefreshHash {
		return nil, ErrOAuthGrantInvalid
	}
	var grant OAuthGrant
	var replay bool
	rotate := func(tx *gorm.DB) error {
		now := time.Now().Unix()
		var token OAuthRefreshToken
		// Locate first, then consistently lock the grant before its token. This
		// serializes rotation with revocation, narrowing and initial issuance.
		if err := tx.Where("token_hash = ?", hash).First(&token).Error; err != nil {
			if errors.Is(err, gorm.ErrRecordNotFound) {
				return ErrOAuthGrantInvalid
			}
			return err
		}
		if err := lockForUpdate(tx).Where("id = ? AND oauth_client_id = ?", token.GrantID, clientID).First(&grant).Error; err != nil {
			if errors.Is(err, gorm.ErrRecordNotFound) {
				return ErrOAuthGrantInvalid
			}
			return err
		}
		if grant.RevokedAt != 0 || grant.ExpiresAt <= now || token.GrantVersion != grant.Version {
			return ErrOAuthGrantInvalid
		}
		if err := lockForUpdate(tx).First(&token, token.ID).Error; err != nil {
			return err
		}
		if token.ConsumedAt != 0 {
			replay = true
			return tx.Model(&OAuthGrant{}).Where("id = ? AND revoked_at = 0", grant.ID).
				Updates(map[string]interface{}{"revoked_at": now, "version": gorm.Expr("version + 1")}).Error
		}
		if token.ExpiresAt <= now {
			return ErrOAuthGrantInvalid
		}
		consumed := tx.Model(&OAuthRefreshToken{}).Where("id = ? AND consumed_at = 0", token.ID).Update("consumed_at", now)
		if consumed.Error != nil {
			return consumed.Error
		}
		if consumed.RowsAffected != 1 {
			replay = true
			return tx.Model(&OAuthGrant{}).Where("id = ? AND revoked_at = 0", grant.ID).
				Updates(map[string]interface{}{"revoked_at": now, "version": gorm.Expr("version + 1")}).Error
		}
		return insertOAuthTokenPair(tx, &grant, nextAccessHash, nextRefreshHash, accessExpiresAt, refreshExpiresAt, now)
	}
	// SQLite cannot upgrade an existing read snapshot after another writer
	// commits. Retry from a fresh transaction so a simultaneous refresh loser
	// sees the consumed ancestor and commits the same replay revocation.
	for attempt := 0; ; attempt++ {
		grant, replay = OAuthGrant{}, false
		err := DB.Transaction(rotate)
		if err == nil {
			break
		}
		if !retryableOAuthSQLiteConflict(err, attempt) {
			return nil, err
		}
		time.Sleep(time.Duration(5<<attempt) * time.Millisecond)
	}
	if replay {
		return nil, ErrOAuthRefreshReplay
	}
	return &grant, nil
}

// RevokeOAuthToken follows RFC 7009's non-disclosing success behavior for an
// unknown token or a token belonging to a different authenticated client.
func RevokeOAuthToken(hash string, clientID int) error {
	if !validOAuthTokenHash(hash) || clientID <= 0 {
		return nil
	}
	var access OAuthAccessToken
	err := DB.Where("token_hash = ?", hash).First(&access).Error
	grantID := access.GrantID
	if errors.Is(err, gorm.ErrRecordNotFound) {
		var refresh OAuthRefreshToken
		if err = DB.Where("token_hash = ?", hash).First(&refresh).Error; err == nil {
			grantID = refresh.GrantID
		}
	}
	if errors.Is(err, gorm.ErrRecordNotFound) {
		return nil
	}
	if err != nil {
		return err
	}
	return DB.Model(&OAuthGrant{}).Where("id = ? AND oauth_client_id = ? AND revoked_at = 0", grantID, clientID).
		Updates(map[string]interface{}{"revoked_at": time.Now().Unix(), "version": gorm.Expr("version + 1")}).Error
}

func RevokeOAuthGrantForUser(grantID, userID int) (bool, error) {
	if grantID <= 0 || userID <= 0 {
		return false, nil
	}
	result := DB.Model(&OAuthGrant{}).Where("id = ? AND user_id = ? AND revoked_at = 0", grantID, userID).
		Updates(map[string]interface{}{"revoked_at": time.Now().Unix(), "version": gorm.Expr("version + 1")})
	return result.RowsAffected != 0, result.Error
}

func ListOAuthGrantsForUser(userID int) ([]OAuthGrant, error) {
	grants := make([]OAuthGrant, 0)
	if userID <= 0 {
		return grants, nil
	}
	err := DB.Where("user_id = ? AND revoked_at = 0 AND expires_at > ?", userID, time.Now().Unix()).
		Order("created_at desc, id desc").Find(&grants).Error
	return grants, err
}

// NarrowOAuthGrant permits only subset changes; a client must obtain a fresh
// explicit grant afterward because the version change invalidates its tokens.
func NarrowOAuthGrant(grantID, userID int, scopes, resources []string) (*OAuthGrant, error) {
	scopes = normalizeOauthScopes(scopes)
	resources = normalizeOauthScopes(resources)
	if grantID <= 0 || userID <= 0 || len(scopes) == 0 || len(resources) == 0 {
		return nil, ErrOAuthGrantInvalid
	}
	var grant OAuthGrant
	err := DB.Transaction(func(tx *gorm.DB) error {
		if err := lockForUpdate(tx).Where("id = ? AND user_id = ? AND revoked_at = 0 AND expires_at > ?", grantID, userID, time.Now().Unix()).First(&grant).Error; err != nil {
			if errors.Is(err, gorm.ErrRecordNotFound) {
				return ErrOAuthGrantInvalid
			}
			return err
		}
		var currentResources []string
		if err := common.UnmarshalJsonStr(grant.Resources, &currentResources); err != nil {
			return ErrOAuthGrantInvalid
		}
		for _, subset := range []struct{ requested, current []string }{
			{scopes, strings.Fields(grant.Scopes)}, {resources, currentResources},
		} {
			allowed := make(map[string]struct{}, len(subset.current))
			for _, value := range subset.current {
				allowed[value] = struct{}{}
			}
			for _, value := range subset.requested {
				if _, ok := allowed[value]; !ok {
					return ErrOAuthScopeExpansion
				}
			}
		}
		encodedResources, err := common.Marshal(resources)
		if err != nil {
			return err
		}
		result := tx.Model(&OAuthGrant{}).Where("id = ? AND version = ? AND revoked_at = 0", grant.ID, grant.Version).
			Updates(map[string]interface{}{"scopes": strings.Join(scopes, " "), "resources": string(encodedResources), "version": gorm.Expr("version + 1")})
		if result.Error != nil {
			return result.Error
		}
		if result.RowsAffected != 1 {
			return ErrOAuthGrantInvalid
		}
		grant.Scopes = strings.Join(scopes, " ")
		grant.Resources = string(encodedResources)
		grant.Version++
		return nil
	})
	if err != nil {
		return nil, err
	}
	return &grant, nil
}

// CleanupExpiredOAuthGrants retains complete token families until 30 days
// after their absolute expiry. Keeping consumed ancestors until then preserves
// replay detection for every still-live grant. Each batch commits atomically.
func CleanupExpiredOAuthGrants(now time.Time) (int64, error) {
	cutoff := now.Add(-30 * 24 * time.Hour).Unix()
	var removed int64
	for {
		var batchCount int64
		err := DB.Transaction(func(tx *gorm.DB) error {
			var grants []OAuthGrant
			if err := lockForUpdate(tx).Where("expires_at < ?", cutoff).Order("id").Limit(200).Find(&grants).Error; err != nil {
				return err
			}
			if len(grants) == 0 {
				return nil
			}
			ids := make([]int, len(grants))
			for index, grant := range grants {
				ids[index] = grant.ID
			}
			if err := tx.Where("grant_id IN ?", ids).Delete(&OAuthAccessToken{}).Error; err != nil {
				return err
			}
			if err := tx.Where("grant_id IN ?", ids).Delete(&OAuthRefreshToken{}).Error; err != nil {
				return err
			}
			result := tx.Where("id IN ? AND expires_at < ?", ids, cutoff).Delete(&OAuthGrant{})
			batchCount = result.RowsAffected
			return result.Error
		})
		if err != nil {
			return removed, err
		}
		removed += batchCount
		if batchCount < 200 {
			return removed, nil
		}
	}
}
